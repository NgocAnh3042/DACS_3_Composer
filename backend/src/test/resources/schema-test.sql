CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firebase_uid VARCHAR(128) NOT NULL UNIQUE,
    name VARCHAR(160) NOT NULL DEFAULT '',
    email VARCHAR(254) NULL UNIQUE,
    phone VARCHAR(32) NULL,
    address_line VARCHAR(500) NULL,
    role VARCHAR(32) NOT NULL DEFAULT 'customer',
    avatar_url VARCHAR(1024) NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'active',
    last_login_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL
);

CREATE TABLE IF NOT EXISTS merchants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT NOT NULL,
    brand_name VARCHAR(180) NOT NULL,
    hotline VARCHAR(32), status VARCHAR(32) NOT NULL DEFAULT 'active'
);

CREATE TABLE IF NOT EXISTS stores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id BIGINT NOT NULL,
    name VARCHAR(180) NOT NULL,
    description VARCHAR(2000) NULL,
    logo_url VARCHAR(1024) NULL,
    cover_url VARCHAR(1024) NULL,
    address_line VARCHAR(500) NULL,
    latitude DECIMAL(10,7) NULL,
    longitude DECIMAL(10,7) NULL,
    phone VARCHAR(32) NULL,
    email VARCHAR(254) NULL,
    is_open BOOLEAN NOT NULL DEFAULT TRUE,
    order_notify BOOLEAN NOT NULL DEFAULT TRUE,
    sound_notify BOOLEAN NOT NULL DEFAULT TRUE,
    push_notify BOOLEAN NOT NULL DEFAULT TRUE,
    email_notify BOOLEAN NOT NULL DEFAULT FALSE,
    promo_notify BOOLEAN NOT NULL DEFAULT TRUE,
    status VARCHAR(32) NOT NULL DEFAULT 'active',
    rating_avg DECIMAL(3,2) NOT NULL DEFAULT 0,
    rating_count INT NOT NULL DEFAULT 0,
    avg_prep_minutes SMALLINT NULL,
    open_time TIME NULL,
    close_time TIME NULL,
    deleted_at TIMESTAMP NULL
);

CREATE TABLE IF NOT EXISTS store_staff (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    staff_role VARCHAR(20) NOT NULL DEFAULT 'manager',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_test_store_staff UNIQUE(store_id,user_id)
);

CREATE TABLE IF NOT EXISTS menu_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id BIGINT NOT NULL,
    name VARCHAR(120) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS dishes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id BIGINT NOT NULL,
    menu_category_id BIGINT NULL,
    platform_category_id BIGINT NULL,
    name VARCHAR(180) NOT NULL,
    description VARCHAR(2000) NULL,
    image_url VARCHAR(1024) NULL,
    price DECIMAL(12,2) NOT NULL,
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    rating_avg DECIMAL(3,2) NOT NULL DEFAULT 0,
    rating_count INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL
);

CREATE TABLE IF NOT EXISTS vouchers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id BIGINT NULL,
    code VARCHAR(64) NOT NULL,
    title VARCHAR(180) NOT NULL,
    description VARCHAR(2000) NULL,
    image_url VARCHAR(1500) NULL,
    discount_type VARCHAR(32) NOT NULL,
    discount_value DECIMAL(12,2) NOT NULL,
    max_discount DECIMAL(12,2) NULL,
    min_order_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
    usage_limit INT NULL,
    used_count INT NOT NULL DEFAULT 0,
    starts_at TIMESTAMP NULL,
    ends_at TIMESTAMP NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL,
    label VARCHAR(60) NOT NULL DEFAULT 'Địa chỉ', receiver_name VARCHAR(160) NOT NULL,
    receiver_phone VARCHAR(32) NOT NULL, address_line VARCHAR(500) NOT NULL,
    ward VARCHAR(120), district VARCHAR(120), city VARCHAR(120), latitude DECIMAL(10,7), longitude DECIMAL(10,7),
    is_default BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code VARCHAR(40) NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL, store_id BIGINT NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'pending', receiver_name VARCHAR(160) NOT NULL,
    receiver_phone VARCHAR(32) NOT NULL, delivery_address VARCHAR(600) NOT NULL,
    delivery_lat DECIMAL(10,7), delivery_lng DECIMAL(10,7), customer_note VARCHAR(1000),
    subtotal DECIMAL(12,2) NOT NULL, delivery_fee DECIMAL(12,2) NOT NULL DEFAULT 0,
    discount_amount DECIMAL(12,2) NOT NULL DEFAULT 0, total_amount DECIMAL(12,2) NOT NULL,
    payment_method VARCHAR(20) NOT NULL, payment_status VARCHAR(20) NOT NULL DEFAULT 'pending',
    placed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, accepted_at TIMESTAMP, ready_at TIMESTAMP,
    picked_up_at TIMESTAMP, delivered_at TIMESTAMP, cancelled_at TIMESTAMP, cancel_reason VARCHAR(500),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL,
    dish_id BIGINT, dish_name VARCHAR(180) NOT NULL, unit_price DECIMAL(12,2) NOT NULL,
    quantity SMALLINT NOT NULL, line_total DECIMAL(12,2) NOT NULL, note VARCHAR(500),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS order_status_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL,
    status VARCHAR(32) NOT NULL, note VARCHAR(500), actor_user_id BIGINT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS order_vouchers (
    order_id BIGINT NOT NULL, voucher_id BIGINT NOT NULL, discount_amount DECIMAL(12,2) NOT NULL,
    PRIMARY KEY(order_id,voucher_id)
);
CREATE TABLE IF NOT EXISTS payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL,
    provider VARCHAR(20) NOT NULL, method VARCHAR(40) NOT NULL, payos_order_code BIGINT,
    payment_link_id VARCHAR(120), gateway_txn_id VARCHAR(160), amount DECIMAL(12,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pending', checkout_url VARCHAR(1500),
    paid_at TIMESTAMP, failed_at TIMESTAMP, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, CONSTRAINT reject_test_rollback_amount CHECK(amount <> 105000)
);
CREATE TABLE IF NOT EXISTS drivers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL UNIQUE,
    vehicle_type VARCHAR(60), vehicle_model VARCHAR(120), license_plate VARCHAR(32),
    work_status VARCHAR(20) NOT NULL DEFAULT 'offline', rating_avg DECIMAL(3,2) DEFAULT 0,
    completed_trips INT NOT NULL DEFAULT 0, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL UNIQUE,
    driver_id BIGINT, status VARCHAR(20) NOT NULL DEFAULT 'unassigned', delivery_fee DECIMAL(12,2) DEFAULT 0,
    driver_earning DECIMAL(12,2) DEFAULT 0, assigned_at TIMESTAMP, accepted_at TIMESTAMP,
    picked_up_at TIMESTAMP, delivered_at TIMESTAMP, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL,
    type VARCHAR(60) NOT NULL, title VARCHAR(180) NOT NULL, body VARCHAR(1000) NOT NULL,
    related_order_id BIGINT, is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, read_at TIMESTAMP
);
CREATE TABLE IF NOT EXISTS user_device_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    fcm_token VARCHAR(512) NOT NULL UNIQUE,
    platform VARCHAR(20) NOT NULL DEFAULT 'android',
    last_seen_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS activity_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT NOT NULL,
    store_id BIGINT,
    type VARCHAR(60) NOT NULL,
    title VARCHAR(180) NOT NULL,
    description VARCHAR(1000),
    details VARCHAR(2000),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS payment_webhook_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT,
    provider_event_id VARCHAR(180) UNIQUE,
    payload_hash CHAR(64) NOT NULL,
    event_type VARCHAR(100) NOT NULL,
    received_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMP,
    process_status VARCHAR(20) DEFAULT 'received'
);
CREATE TABLE IF NOT EXISTS conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT,
    type VARCHAR(32) NOT NULL DEFAULT 'customer_store',
    created_by BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'open',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS conversation_participants (
    conversation_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    joined_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    last_read_at TIMESTAMP,
    PRIMARY KEY(conversation_id,user_id)
);
CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    sender_user_id BIGINT NOT NULL,
    message_type VARCHAR(20) NOT NULL DEFAULT 'text',
    content VARCHAR(4000),
    image_url VARCHAR(1500),
    is_seen BOOLEAN NOT NULL DEFAULT FALSE,
    is_delivered BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP
);
